-- ============================================================
-- 249_lead_source_web_form.sql — where a contact came from, and a
-- public web form that creates leads.
--
--  * contacts.lead_source: one of ad, web_form, broadcast, manual,
--    import, compass, other; NULL = unknown (every row that existed
--    before this migration stays NULL: nothing is guessed).
--    contacts.lead_source_detail: a small jsonb object (≤ 4 KB) saying
--    which ad / page / file. Both are plain columns: any contact writer
--    may set them at insert (the contact form writes 'manual', CSV
--    import 'import') and an admin may correct them. Automatic writers
--    (the Meta ad referral on a first inbound, the web form) only ever
--    fill an EMPTY source, through contact_set_lead_source_if_empty
--    (service role), so the first known source wins and a person's
--    correction is never overwritten.
--  * web_lead_forms: one row per workspace (account_id is the key), a
--    64-hex token that is the form's public address (/f/<token>), the
--    on/off switch (OFF by default) and the origins allowed to post to
--    it from another site. RLS forced, no policy, no client grant: the
--    token is never readable by anon. Owners/admins read and write it
--    only through web_form_get / web_form_set (authenticated, checking
--    the caller's ACTIVE account role); the token is generated by
--    web_form_set (on first save and on rotate), never by a client.
--  * web_form_submit (service role only; the public route calls it):
--    unknown and disabled tokens answer the same {status:'not_found'};
--    the phone arrives normalised by the app (validateContactPhone:
--    international digits, no '+'); finds the contact by
--    phone_normalized or creates it owned by the workspace owner
--    (accounts.owner_user_id: contacts need a user_id and an
--    unassigned lead belongs to nobody else); fills only EMPTY name and
--    email (a name equal to the number, which inbound writes when a
--    sender has no profile name, counts as empty); sets lead_source
--    'web_form' if empty; and opens a follow_up task (source
--    'automation', no assignee, linked to the contact, so admins see it
--    and anyone who can see the contact). The same contact submitting
--    again within 10 minutes opens no second task (per-(account, phone)
--    advisory lock). It never sends anything and never writes a consent
--    column (opted_out_at, opt-in, do-not-contact).
--
-- Apply as a superuser or BYPASSRLS role (the functions read an
-- RLS-forced table as their owner). Re-runnable. Asserted by
-- supabase/ci/verify-web-lead-form.sql. docs/web-form.md is the
-- contract.
-- ============================================================

SET lock_timeout = '5s';

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = current_user AND (rolsuper OR rolbypassrls)) THEN
    RAISE EXCEPTION '249 must be applied by a superuser or BYPASSRLS role (the web form functions read an RLS-forced table)';
  END IF;
END $$;

-- ---------- 1. contacts.lead_source ----------

ALTER TABLE public.contacts ADD COLUMN IF NOT EXISTS lead_source text NULL;
ALTER TABLE public.contacts
  ADD COLUMN IF NOT EXISTS lead_source_detail jsonb NOT NULL DEFAULT '{}'::jsonb;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'public.contacts'::regclass
       AND conname = 'contacts_lead_source_check') THEN
    ALTER TABLE public.contacts ADD CONSTRAINT contacts_lead_source_check
      CHECK (lead_source IS NULL OR lead_source IN (
        'ad', 'web_form', 'broadcast', 'manual', 'import', 'compass', 'other'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'public.contacts'::regclass
       AND conname = 'contacts_lead_source_detail_check') THEN
    ALTER TABLE public.contacts ADD CONSTRAINT contacts_lead_source_detail_check
      CHECK (jsonb_typeof(lead_source_detail) = 'object'
             AND octet_length(lead_source_detail::text) <= 4096);
  END IF;
END $$;

-- The Contacts screen's Source filter and campaign audiences.
CREATE INDEX IF NOT EXISTS idx_contacts_lead_source
  ON public.contacts (account_id, lead_source)
  WHERE lead_source IS NOT NULL;

-- Fill an empty source; true when it wrote. A source already set (by a
-- person, an import or an earlier automatic writer) is left alone.
CREATE OR REPLACE FUNCTION public.contact_set_lead_source_if_empty(
  p_account uuid, p_contact uuid, p_source text, p_detail jsonb)
RETURNS boolean
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_n integer;
  v_detail jsonb := CASE
    WHEN p_detail IS NOT NULL AND jsonb_typeof(p_detail) = 'object'
         AND octet_length(p_detail::text) <= 4096
    THEN p_detail ELSE '{}'::jsonb END;
BEGIN
  IF p_source IS NULL OR p_source NOT IN (
       'ad', 'web_form', 'broadcast', 'manual', 'import', 'compass', 'other') THEN
    RAISE EXCEPTION 'Unknown lead source: %', coalesce(p_source, 'NULL')
      USING ERRCODE = '22023', HINT = 'bad_source';
  END IF;
  UPDATE public.contacts c
     SET lead_source = p_source,
         lead_source_detail = v_detail
   WHERE c.id = p_contact
     AND c.account_id = p_account
     AND c.lead_source IS NULL;
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n > 0;
END;
$$;

REVOKE ALL ON FUNCTION public.contact_set_lead_source_if_empty(uuid, uuid, text, jsonb)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.contact_set_lead_source_if_empty(uuid, uuid, text, jsonb)
  TO service_role;

COMMENT ON FUNCTION public.contact_set_lead_source_if_empty(uuid, uuid, text, jsonb) IS
  'Set contacts.lead_source (+ detail) only while it is NULL; true when it wrote. Service role. Migration 249.';

-- ---------- 2. web_lead_forms ----------

CREATE TABLE IF NOT EXISTS public.web_lead_forms (
  account_id      uuid PRIMARY KEY REFERENCES public.accounts(id) ON DELETE CASCADE,
  token           text NOT NULL,
  enabled         boolean NOT NULL DEFAULT false,
  allowed_origins text[] NOT NULL DEFAULT '{}',
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT web_lead_forms_token_key UNIQUE (token),
  CONSTRAINT web_lead_forms_token_check CHECK (token ~ '^[0-9a-f]{64}$'),
  CONSTRAINT web_lead_forms_origins_check CHECK (cardinality(allowed_origins) <= 20)
);

ALTER TABLE public.web_lead_forms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.web_lead_forms FORCE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.web_lead_forms FROM PUBLIC, anon, authenticated, service_role;

-- 64 hex characters from two v4 UUIDs: 244 random bits (the fixed
-- version and variant nibbles carry none). gen_random_uuid is core
-- Postgres and draws from the strong random source, so no extension.
CREATE OR REPLACE FUNCTION public.web_form_new_token()
RETURNS text
LANGUAGE sql
VOLATILE
SET search_path = ''
AS $$
  SELECT replace(gen_random_uuid()::text, '-', '')
      || replace(gen_random_uuid()::text, '-', '');
$$;

REVOKE ALL ON FUNCTION public.web_form_new_token() FROM PUBLIC, anon, authenticated, service_role;

-- An https origin as a browser sends it: scheme, lower-case host,
-- optional port, nothing else. TS mirror: normalizeAllowedOrigin
-- (src/lib/web-form/origin.ts).
CREATE OR REPLACE FUNCTION public.web_form_origin_ok(p_origin text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT p_origin IS NOT NULL
     AND char_length(p_origin) <= 200
     AND p_origin ~ '^https://[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*(:[0-9]{1,5})?$';
$$;

REVOKE ALL ON FUNCTION public.web_form_origin_ok(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.web_form_origin_ok(text) TO authenticated, service_role;

-- The caller's active workspace's form. Owner/admin only. Before the
-- first save there is no row: enabled false, no token.
CREATE OR REPLACE FUNCTION public.web_form_get()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_acct uuid := public.current_account_id();
  f public.web_lead_forms%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL OR v_acct IS NULL OR public.current_role_rank() < 4 THEN
    RAISE EXCEPTION 'Only an owner or admin can see the web form'
      USING ERRCODE = '42501', HINT = 'not_admin';
  END IF;
  SELECT * INTO f FROM public.web_lead_forms w WHERE w.account_id = v_acct;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('enabled', false, 'token', NULL,
      'allowed_origins', '[]'::jsonb, 'updated_at', NULL);
  END IF;
  RETURN jsonb_build_object('enabled', f.enabled, 'token', f.token,
    'allowed_origins', to_jsonb(f.allowed_origins), 'updated_at', f.updated_at);
END;
$$;

REVOKE ALL ON FUNCTION public.web_form_get() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.web_form_get() TO authenticated;

-- Save the switch and the origins; p_rotate issues a new token (the old
-- link and every embedded snippet stop working at once). The first save
-- creates the row and its token.
CREATE OR REPLACE FUNCTION public.web_form_set(
  p_enabled boolean, p_allowed_origins text[], p_rotate boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_acct uuid := public.current_account_id();
  v_origins text[];
  v_bad text;
BEGIN
  IF auth.uid() IS NULL OR v_acct IS NULL OR public.current_role_rank() < 4 THEN
    RAISE EXCEPTION 'Only an owner or admin can change the web form'
      USING ERRCODE = '42501', HINT = 'not_admin';
  END IF;
  IF p_enabled IS NULL THEN
    RAISE EXCEPTION 'The switch is required'
      USING ERRCODE = '22023', HINT = 'bad_settings';
  END IF;
  SELECT coalesce(array_agg(DISTINCT o ORDER BY o), '{}')
    INTO v_origins
    FROM unnest(coalesce(p_allowed_origins, '{}')) AS o;
  IF cardinality(v_origins) > 20 THEN
    RAISE EXCEPTION 'At most 20 allowed origins'
      USING ERRCODE = '22023', HINT = 'too_many_origins';
  END IF;
  SELECT o INTO v_bad FROM unnest(v_origins) AS o
   WHERE NOT public.web_form_origin_ok(o) LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'Not an https origin: %', left(v_bad, 80)
      USING ERRCODE = '22023', HINT = 'bad_origin';
  END IF;

  INSERT INTO public.web_lead_forms AS w
         (account_id, token, enabled, allowed_origins)
  VALUES (v_acct, public.web_form_new_token(), p_enabled, v_origins)
  ON CONFLICT (account_id) DO UPDATE
     SET enabled = EXCLUDED.enabled,
         allowed_origins = EXCLUDED.allowed_origins,
         token = CASE WHEN coalesce(p_rotate, false)
                      THEN EXCLUDED.token ELSE w.token END,
         updated_at = now();

  RETURN public.web_form_get();
END;
$$;

REVOKE ALL ON FUNCTION public.web_form_set(boolean, text[], boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.web_form_set(boolean, text[], boolean) TO authenticated;

-- What the public route and the hosted page need: NULL for an unknown,
-- disabled or archived workspace's token (indistinguishable on
-- purpose), else its allowed origins. Never the account id.
CREATE OR REPLACE FUNCTION public.web_form_public_config(p_token text)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT jsonb_build_object('allowed_origins', to_jsonb(w.allowed_origins))
    FROM public.web_lead_forms w
    JOIN public.accounts a ON a.id = w.account_id
   WHERE p_token ~ '^[0-9a-f]{64}$'
     AND w.token = p_token
     AND w.enabled
     AND a.archived_at IS NULL;
$$;

REVOKE ALL ON FUNCTION public.web_form_public_config(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.web_form_public_config(text) TO service_role;

-- One submission. See the header for the rules.
CREATE OR REPLACE FUNCTION public.web_form_submit(
  p_token text, p_name text, p_phone text, p_email text, p_message text,
  p_meta jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_acct    uuid;
  v_owner   uuid;
  v_name    text := nullif(left(regexp_replace(coalesce(p_name, ''), '^[[:space:]]+|[[:space:]]+$', '', 'g'), 120), '');
  v_email   text := lower(nullif(left(btrim(coalesce(p_email, '')), 254), ''));
  v_message text := nullif(left(regexp_replace(coalesce(p_message, ''), '^[[:space:]]+|[[:space:]]+$', '', 'g'), 2000), '');
  v_page    text;
  v_contact uuid;
  v_created boolean := false;
  v_task    boolean := false;
  v_detail  jsonb;
BEGIN
  SELECT w.account_id, a.owner_user_id INTO v_acct, v_owner
    FROM public.web_lead_forms w
    JOIN public.accounts a ON a.id = w.account_id
   WHERE p_token ~ '^[0-9a-f]{64}$'
     AND w.token = p_token
     AND w.enabled
     AND a.archived_at IS NULL;
  IF v_acct IS NULL THEN
    RETURN jsonb_build_object('status', 'not_found');
  END IF;

  IF p_phone IS NULL OR p_phone !~ '^[1-9][0-9]{9,14}$' THEN
    RAISE EXCEPTION 'The phone number must be international digits'
      USING ERRCODE = '22023', HINT = 'bad_phone';
  END IF;
  IF v_email IS NOT NULL AND v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN
    v_email := NULL;
  END IF;
  IF p_meta IS NOT NULL AND jsonb_typeof(p_meta) = 'object'
     AND jsonb_typeof(p_meta -> 'page_url') = 'string' THEN
    v_page := nullif(left(p_meta ->> 'page_url', 500), '');
  END IF;
  v_detail := jsonb_build_object('form', 'web', 'submitted_at', now())
    || CASE WHEN v_page IS NULL THEN '{}'::jsonb
            ELSE jsonb_build_object('page_url', v_page) END;

  -- One submission per (workspace, number) at a time: the dedupe
  -- window below and the find-or-create are decided under this lock.
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtext('web_form_submit'),
    pg_catalog.hashtext(v_acct::text || ':' || p_phone));

  SELECT c.id INTO v_contact
    FROM public.contacts c
   WHERE c.account_id = v_acct AND c.phone_normalized = p_phone
   LIMIT 1;

  IF v_contact IS NULL THEN
    INSERT INTO public.contacts (account_id, user_id, phone, name, email)
    VALUES (v_acct, v_owner, p_phone, v_name, v_email)
    ON CONFLICT (account_id, phone_normalized) WHERE phone_normalized <> ''
    DO NOTHING
    RETURNING id INTO v_contact;
    IF v_contact IS NOT NULL THEN
      v_created := true;
    ELSE
      -- An inbound message created it meanwhile.
      SELECT c.id INTO v_contact
        FROM public.contacts c
       WHERE c.account_id = v_acct AND c.phone_normalized = p_phone
       LIMIT 1;
    END IF;
  END IF;

  IF NOT v_created THEN
    -- Fill only what is empty. Consent columns are never written.
    UPDATE public.contacts c
       SET name = CASE
             WHEN v_name IS NOT NULL
              AND (c.name IS NULL OR c.name ~ '^[[:space:]]*$'
                   OR regexp_replace(c.name, '\D', '', 'g') = c.phone_normalized)
             THEN v_name ELSE c.name END,
           email = CASE
             WHEN v_email IS NOT NULL AND (c.email IS NULL OR c.email ~ '^[[:space:]]*$')
             THEN v_email ELSE c.email END
     WHERE c.id = v_contact
       AND ((v_name IS NOT NULL
             AND (c.name IS NULL OR c.name ~ '^[[:space:]]*$'
                  OR regexp_replace(c.name, '\D', '', 'g') = c.phone_normalized))
         OR (v_email IS NOT NULL AND (c.email IS NULL OR c.email ~ '^[[:space:]]*$')));
  END IF;

  PERFORM public.contact_set_lead_source_if_empty(v_acct, v_contact, 'web_form', v_detail);

  -- At most one "New web lead" task per contact per 10 minutes: a
  -- double click, a refresh or a bot repeating itself opens nothing new.
  IF NOT EXISTS (
    SELECT 1 FROM public.tasks t
     WHERE t.contact_id = v_contact
       AND t.account_id = v_acct
       AND t.source = 'automation'
       AND t.source_ref LIKE 'web_form:%'
       AND t.created_at > now() - interval '10 minutes') THEN
    INSERT INTO public.tasks
           (account_id, kind, title, note, contact_id, source, source_ref, meta)
    VALUES (v_acct, 'follow_up', 'New web lead', v_message, v_contact,
            'automation',
            'web_form:' || v_contact::text || ':'
              || floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint::text,
            jsonb_build_object('web_form', true)
              || CASE WHEN v_page IS NULL THEN '{}'::jsonb
                      ELSE jsonb_build_object('page_url', v_page) END)
    ON CONFLICT (account_id, source, source_ref) DO NOTHING;
    v_task := FOUND;
  END IF;

  RETURN jsonb_build_object('status', 'ok', 'contact_id', v_contact,
    'contact_created', v_created, 'task_created', v_task);
END;
$$;

REVOKE ALL ON FUNCTION public.web_form_submit(text, text, text, text, text, jsonb)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.web_form_submit(text, text, text, text, text, jsonb)
  TO service_role;

